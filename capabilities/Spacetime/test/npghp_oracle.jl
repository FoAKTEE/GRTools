# npghp_oracle.jl — first-principles NP spin-coefficient ORACLE (test-only referee for G-B2/G-F5).
#
# Promoted from scratchpad/npghp_moveB/np_spincoeff_oracle.jl (R_oracle.md, verdict [SOLID]).
# Computes the full Kerr Kinnersley NP spin-coefficient table DIRECTLY from Spacetime's own
#   * metric            Spacetime.kerr_metric(a,r,θ; coords)            (:BL, :In, :Out)
#   * Kinnersley tetrad Spacetime.kinnersley_tetrad(a,r,θ; coords)      (contravariant legs)
#   * Christoffels      Spacetime.christoffel(a,r,θ; coords=:BL)        (ANALYTIC ∂g, :BL only)
#                       OR central FD of the ANALYTIC metric            (:In / :Out, F5)
# by forming covariant derivatives of the LOWERED tetrad legs and contracting. NO new deps
# (uses only exported Spacetime symbols). Type-generic: Float64 and BigFloat.
#
# For :BL the connection term −Γ^λ_{μν} leg_λ uses Spacetime's ANALYTIC Christoffels (exact) and
# the ONLY finite difference is on the tetrad-leg partials ∂_ν(leg_μ) (BL path bit-UNCHANGED).
# For :In / :Out the analytic-Γ shortcut is unavailable (Spacetime.christoffel is BL-only), so the
# Christoffels are built by CENTRAL FD of the analytic chart metric kerr_metric(:In/:Out) at step
# hΓ (the metric is v/φ̃-independent, so only the r,θ partials are nonzero — same structure as BL);
# this is a SECOND FD layer on top of the leg FD, at a documented precision cost (G-F5 sweeps hΓ ∈
# {1e-6,1e-7} and gates at the demonstrated floor with margin). ψ₂ additionally FDs the Christoffels
# once more to build Riemann (vacuum ⇒ Weyl = Riemann).
#
# [AXIOM] sign pins (R_oracle.md §4, verified there against the in-repo closed forms + MG oracle):
#   1. Overall minus:  ρ = −l_{μ;ν} m^μ m̄^ν  (etc.) — the choice giving ρ=−1/ζ, μ=−Δ/2Σζ, ρ=−1/r.
#   2. n-leg block (π,ν,μ,λ) is the raw n_{μ;ν} contraction with a PLUS.
#   3. Riemann/Weyl → ψ₂ needs NO extra sign (MTW/Wald R + ψ₂=C l m m̄ n gives −M/ζ³).
#   4. GHP prime relations ρ′=−μ, ε′=−γ — NOT free here: the primed table is generated by the
#      LEG-SWAP (l↔n, m↔m̄) and compared to Spacetime.NPGHP.ghp_spincoeff (G-B2 primed check).
#
# The leg-swap variant (primed=true) reorders the four contravariant legs to (n, l, m̄, m) and
# applies the SAME NP contraction template, so its output IS the NP table of the primed tetrad,
# i.e. the primed spin coefficients ρ′, μ′, τ′, … — the independent referee for the prime map.
module NPGHPOracle

using Spacetime
const ST = Spacetime

# leg tuple in the requested order: unprimed (l,n,m,m̄) or primed/leg-swapped (n,l,m̄,m).
function _legs(a, r, θ; primed::Bool = false, coords::Symbol = :BL)
    l, n, m, mb = ST.kinnersley_tetrad(a, r, θ; coords = coords)
    primed ? (n, l, mb, m) : (l, n, m, mb)
end

# lowered legs as a 4×4 matrix (column k = lowered k-th leg of the ordered tuple).
function _lowered_matrix(a, r, θ, legs; coords::Symbol = :BL)
    g = ST.kerr_metric(a, r, θ; coords = coords)
    hcat((g * e for e in legs)...)
end

# Γ^λ_{μν} in chart `coords`: analytic for :BL (BL path bit-unchanged); central FD of the analytic
# chart metric for :In/:Out (the metric is v/φ̃-independent ⇒ only ∂_r, ∂_θ are nonzero).
function _christoffel(a, r, θ; coords::Symbol = :BL, hΓ = 1e-6)
    coords === :BL && return ST.christoffel(a, r, θ; coords = :BL)
    g  = ST.kerr_metric(a, r, θ; coords = coords)
    T  = eltype(g)
    gi = ST.kerr_metric_inv(a, r, θ; coords = coords)
    gr = (ST.kerr_metric(a, r + hΓ, θ; coords = coords) .-
          ST.kerr_metric(a, r - hΓ, θ; coords = coords)) ./ (2hΓ)
    gθ = (ST.kerr_metric(a, r, θ + hΓ; coords = coords) .-
          ST.kerr_metric(a, r, θ - hΓ; coords = coords)) ./ (2hΓ)
    dg = zeros(T, 4, 4, 4); dg[2, :, :] = gr; dg[3, :, :] = gθ
    Γ = zeros(T, 4, 4, 4)
    @inbounds for λ in 1:4, μ in 1:4, ν in 1:4
        acc = zero(T)
        for σ in 1:4
            acc += gi[λ, σ] * (dg[μ, σ, ν] + dg[ν, σ, μ] - dg[σ, μ, ν])
        end
        Γ[λ, μ, ν] = acc / 2
    end
    Γ
end

# D[μ,ν,k] = ∇_ν (leg_k)_μ  (central FD of the leg partials; connection term from _christoffel).
function _covderiv(a, r, θ, h; primed::Bool = false, coords::Symbol = :BL, hΓ = h)
    Γ  = _christoffel(a, r, θ; coords = coords, hΓ = hΓ)   # Γ[λ,μ,ν] = Γ^λ_{μν}
    L0 = _lowered_matrix(a, r, θ, _legs(a, r, θ; primed = primed, coords = coords); coords = coords)
    CT = eltype(L0)
    Lrp = _lowered_matrix(a, r + h, θ, _legs(a, r + h, θ; primed = primed, coords = coords); coords = coords)
    Lrm = _lowered_matrix(a, r - h, θ, _legs(a, r - h, θ; primed = primed, coords = coords); coords = coords)
    Ltp = _lowered_matrix(a, r, θ + h, _legs(a, r, θ + h; primed = primed, coords = coords); coords = coords)
    Ltm = _lowered_matrix(a, r, θ - h, _legs(a, r, θ - h; primed = primed, coords = coords); coords = coords)
    dr = (Lrp - Lrm) / (2h)
    dθ = (Ltp - Ltm) / (2h)
    D = zeros(CT, 4, 4, 4)
    @inbounds for k in 1:4, μ in 1:4, ν in 1:4
        ∂ = ν == 2 ? dr[μ, k] : ν == 3 ? dθ[μ, k] : zero(CT)
        conn = zero(CT)
        for λ in 1:4
            conn += Γ[λ, μ, ν] * L0[λ, k]
        end
        D[μ, ν, k] = ∂ - conn
    end
    D
end

# contract a covariant-derivative slab D[μ,ν] with contravariant weight vectors X^μ, Y^ν.
_contract(Dslab, X, Y) = sum(X[μ] * Y[ν] * Dslab[μ, ν] for μ in 1:4, ν in 1:4)

"""
    np_spincoeffs(a, r, θ; h, primed=false, coords=:BL, hΓ=h) -> NamedTuple

Full NP spin-coefficient table (κ,ρ,σ,τ,π,ν,μ,λ,ε,γ,β,α) at (a,r,θ) for the Kinnersley tetrad of
chart `coords ∈ (:BL,:In,:Out)` (`primed=false`) or its leg-swapped primed tetrad (`primed=true`,
giving ρ′,μ′,…). Referee for G-B2 (:BL, analytic Γ) and G-F5 (:In/:Out, FD Γ at step `hΓ`).
"""
function np_spincoeffs(a, r, θ; h = 1e-6, primed::Bool = false, coords::Symbol = :BL, hΓ = h)
    e1, e2, e3, e4 = _legs(a, r, θ; primed = primed, coords = coords)   # (l,n,m,m̄) or (n,l,m̄,m)
    D  = _covderiv(a, r, θ, h; primed = primed, coords = coords, hΓ = hΓ)
    D1 = @view D[:, :, 1]; D2 = @view D[:, :, 2]; D3 = @view D[:, :, 3]
    C  = _contract
    κ = -C(D1, e3, e1)
    ρ = -C(D1, e3, e4)
    σ = -C(D1, e3, e3)
    τ = -C(D1, e3, e2)
    π_ = C(D2, e4, e1)
    ν_ = C(D2, e4, e2)
    μ  = C(D2, e4, e3)
    λ  = C(D2, e4, e4)
    ε = -(C(D1, e2, e1) - C(D3, e4, e1)) / 2
    γ = -(C(D1, e2, e2) - C(D3, e4, e2)) / 2
    β = -(C(D1, e2, e3) - C(D3, e4, e3)) / 2
    α = -(C(D1, e2, e4) - C(D3, e4, e4)) / 2
    (; κ, ρ, σ, τ, π = π_, ν = ν_, μ, λ, ε, γ, β, α)
end

"""
    psi2(a, r, θ; h, coords=:BL, hΓ=h) -> Complex

ψ₂ = C_{αβγδ} l^α m^β m̄^γ n^δ from the full Riemann tensor (vacuum ⇒ Weyl = Riemann), FD of the
Christoffels of chart `coords`. For :BL the Christoffels are analytic (BL path bit-unchanged); for
:In/:Out they are the FD-of-metric Christoffels (`_christoffel`, step `hΓ`) FD'd once more — a
FD-of-FD stack whose ψ₂ floor G-F5 measures. Referee for the ψ₂ chart-invariance check.
"""
function psi2(a, r, θ; h = 1e-5, coords::Symbol = :BL, hΓ = h)
    Γ  = _christoffel(a, r, θ; coords = coords, hΓ = hΓ)
    T  = eltype(Γ)
    Γrp = _christoffel(a, r + h, θ; coords = coords, hΓ = hΓ); Γrm = _christoffel(a, r - h, θ; coords = coords, hΓ = hΓ)
    Γtp = _christoffel(a, r, θ + h; coords = coords, hΓ = hΓ); Γtm = _christoffel(a, r, θ - h; coords = coords, hΓ = hΓ)
    dΓ = zeros(T, 4, 4, 4, 4)                            # dΓ[α,ρ,μ,ν] = ∂_α Γ^ρ_{μν}
    dΓ[2, :, :, :] = (Γrp - Γrm) / (2h)
    dΓ[3, :, :, :] = (Γtp - Γtm) / (2h)
    Ru = zeros(T, 4, 4, 4, 4)                            # R^ρ_{σμν}, upper ρ (MTW/Wald)
    @inbounds for ρ in 1:4, σ in 1:4, μ in 1:4, ν in 1:4
        s = dΓ[μ, ρ, ν, σ] - dΓ[ν, ρ, μ, σ]
        for λ in 1:4
            s += Γ[ρ, μ, λ] * Γ[λ, ν, σ] - Γ[ρ, ν, λ] * Γ[λ, μ, σ]
        end
        Ru[ρ, σ, μ, ν] = s
    end
    g  = ST.kerr_metric(a, r, θ; coords = coords)
    Rl = zeros(T, 4, 4, 4, 4)                            # R_{aσμν} = g_{aρ} R^ρ_{σμν}
    @inbounds for a_ in 1:4, σ in 1:4, μ in 1:4, ν in 1:4
        s = zero(T)
        for ρ in 1:4
            s += g[a_, ρ] * Ru[ρ, σ, μ, ν]
        end
        Rl[a_, σ, μ, ν] = s
    end
    l, n, m, mb = ST.kinnersley_tetrad(a, r, θ; coords = coords)
    sum(Rl[α, β, γ, δ] * l[α] * m[β] * mb[γ] * n[δ] for α in 1:4, β in 1:4, γ in 1:4, δ in 1:4)
end

end # module NPGHPOracle
