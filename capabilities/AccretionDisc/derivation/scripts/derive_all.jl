# scripts/derive_all.jl — run the whole route-R3 derivation and its certificate suites, write the
# hand-off artefacts, and print the verbatim log that becomes the node evidence.
#
#   julia --project=capabilities/AccretionDisc/derivation -t4 \
#         capabilities/AccretionDisc/derivation/scripts/derive_all.jl [npts]
#
# Deterministic (fixed seeds); `npts` defaults to 50 exact-rational certificate points.

using Printf

include(joinpath(@__DIR__, "..", "src", "R3Derivation.jl"))
using .R3Derivation
const R3 = R3Derivation

const NPTS = length(ARGS) >= 1 ? parse(Int, ARGS[1]) : 50
const OUT = joinpath(@__DIR__, "..", "out")
mkpath(OUT)

println("=== route R3 — Julia-native derivation of arXiv:2608.17003 ===")
println("julia      : ", VERSION)
println("points     : ", NPTS, "   seed 2608")
println("threads    : ", Threads.nthreads())
println()

t0 = time()
println("--- stage 1: symbolic background, Eqs. (4)-(11) ---")
c1 = R3.stage1_certificates(; npts = NPTS)
t1 = time()
println(@sprintf("stage 1 wall: %.1f s", t1 - t0))
println()

println("--- stage 2: perturbation + reduction, Eqs. (15)-(22), (45)-(49) ---")
c2 = R3.stage2_certificates(; npts = NPTS)
t2 = time()
println(@sprintf("stage 2 wall: %.1f s", t2 - t1))
println()

println("--- stage 2 gate: Newtonian limit vs Eq. (50) of the paper ---")
c2n = R3.newtonian_certificates(; npts = max(6, NPTS ÷ 8))
t3 = time()
println(@sprintf("Newtonian gate wall: %.1f s", t3 - t2))
println()

println("--- stage 3: diagnostics, Eqs. (39)-(43), (69), (72) ---")
c3 = R3.stage3_certificates(; npts = NPTS)
t4 = time()
println(@sprintf("stage 3 wall: %.1f s", t4 - t3))
println()

println("--- structure of the linearised system (drives the reduction order) ---")
for (k, v) in pairs(R3.reduction_structure())
    println(@sprintf("  %-10s %s", k, v))
end
println()

mpath = joinpath(OUT, "R3_master.jls.txt")
dpath = joinpath(OUT, "R3_diagnostics.jls.txt")
R3.write_exports(mpath, R3.master_exports();
                 header = "# R3_master.jls.txt -- GENERATED by derivation/scripts/derive_all.jl\n" *
                          "# route R3 (Julia-native) master system (47)-(49) of arXiv:2608.17003.\n" *
                          "# Consumed by EGD::jd-codegen; NOT a runtime artefact of AccretionDisc.")
R3.write_exports(dpath, R3.diagnostics_exports();
                 header = "# R3_diagnostics.jls.txt -- GENERATED by derivation/scripts/derive_all.jl\n" *
                          "# route R3 (Julia-native) diagnostics integrands (40)-(43),(72) of arXiv:2608.17003.")
println("wrote ", mpath, "  (", filesize(mpath), " bytes)")
println("wrote ", dpath, "  (", filesize(dpath), " bytes)")
println()

allc = vcat(c1, c2, c2n, c3)
println("=== certificate table ===")
print(R3.certificate_table(allc))
println()
npass = count(c -> c.pass, allc)
println(@sprintf("=== SUMMARY === %d/%d PASS   total wall %.1f s", npass, length(allc), time() - t0))
npass == length(allc) || error("route R3: $(length(allc) - npass) certificate(s) FAILED")
