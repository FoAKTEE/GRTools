"""
    AccretionDisc.SpiralWaves

The relativistic spiral-density-wave pipeline of arXiv:2608.17003 (Hegade K R, Yunes et al.:
"Relativistic spiral density waves and disk-EMRI torques" — linear Lagrangian perturbation theory
of a razor-thin, stationary, axisymmetric, purely rotating disc on the Page–Thorne equatorial
line element ds² = −e^{2ν}dt² + e^{2ψ}(dφ − ω̃ dt)² + e^{2μ}dr² + dz², driven by the simplified
gravitational potential of a circular equatorial EMRI).

Design (one file per DAG node, each landed tests-first; the include list below is the planned
dependency ORDER and is uncommented as each node lands — no stub is shipped ahead of its tests):

    # include("background.jl")   # EGD::sw-background LANDED (v0.2.0): disc equilibrium on (ν,ψ,μ,ω̃) —
    #                            #      Ω(r), v, u^t, u_t, u_φ from the exact (11), power laws (12), Ω• (13),
    #                            #      Γ1 (22), κ², r_ISCO, F_{J,0/1} (76); over Spacetime.kerr_equatorial_potentials
    # include("master.jl")       # EGD::sw-master-matrices LANDED (v0.4.0): the 2×2 first-order master
    #                            #      system dy/dr = C y + S, y = (δÛ, −iδû^r) (47) — relativistic C, S
    #                            #      GENERATED by the Julia derivation of route R3 (master_derived.jl),
    #                            #      Newtonian (50a-g), Landau shift (62-63), dΩ/dr; over background + grid
    # include("source.jl")       # EGD::sw-singular-source LANDED (v0.5.0): the singular field h_μν (52) of
    #                            #      the circular EMRI worldline (53)-(55), s0² (58)/(B1), softening (59),
    #                            #      cosine Fourier modes (60) + analytic ∂_r by the periodic trapezoid
    #                            #      rule (node count from the analytic strip), covariant + contravariant,
    #                            #      grid-vectorised `source_modes`; over background
    # include("grid.jl")         # EGD::sw-grid LANDED (v0.3.0): adaptive radial grid (App. C) — r_c (61),
    #                            #      sinh corotation block (C4-5), WKB k (C2,C6), Δr_WKB/smoothMin (C7-10),
    #                            #      cubic-spline node placement, per-mode domain (C1-3); NumericsCore
    # include("solver.jl")       # EGD: implicit two-first-order-equation integrator, sparse
    #                            #      (SparseArrays) banded assembly, boundary conditions
    # include("diagnostics.jl")  # EGD: energy / angular-momentum balance laws, torque per m,
    #                            #      spiral morphology diagnostics
    # include("survey.jl")       # EGD: spin / radius / aspect-ratio / profile surveys, m-cutoff
    #                            #      ~3/h convergence, pressureless-disc comparison

Lives ABOVE `Modes` (the legacy Lin–Shu reduced-operator disc-mode solver) and `Force` (the
Lorenz-closure torque front-end) and reaches Kerr geometry ONLY through `Spacetime`
(`kerr_equatorial_potentials`, `kerr_equatorial_potentials_dr`, `kerr_circular_dtdtau`,
`kerr_isco`, `horizons`). Every primitive is type-generic `{T}`; BigFloat precision is inherited.
Exports are added per landed node; the scaffold exports nothing.
"""
module SpiralWaves

using Spacetime
using SparseArrays
using ..Modes

"The arXiv identifier of the paper this submodule reproduces."
const PAPER = "arXiv:2608.17003"

"""
    sw_version() -> VersionNumber

Version of the `SpiralWaves` submodule API (bumped as DAG nodes land; `v"0.1.0"` = scaffold,
`v"0.2.0"` = background, `v"0.3.0"` = grid, `v"0.4.0"` = master matrices, `v"0.5.0"` = singular source,
`v"0.6.0"` = mode solver, `v"0.7.0"` = diagnostics,
`v"0.8.0"` = survey, `v"0.9.0"` = image synthesis, `v"0.9.1"` = its Cartesian/winding/mode-sweep front end,
`v"0.10.0"` = the Newtonian-limit pipeline (T_Newt of Fig. 5),
`v"0.11.0"` = the controlled grid options `wavenumber = :newtonian|:gr` (E-M5) and
`extent = :inner_fiducial|:outer_fiducial` of EGD::sw-grid-gr-refinement,
`v"0.12.0"` = the inner-boundary RESPONSE instruments of the EGD::fig10 deficit investigation —
the WKB amplitude split / reflection coefficient (`wkb_split`, `wkb_amplitudes`, `mode_amplitudes`),
the first-order WKB impedance closure `solve_mode(…; bc = :wkb1)` and the explicit domain-edge
overrides `build_grid(…; r_in =, r_out =)`; every default unchanged).
"""
sw_version() = v"0.12.0"

# ---- EGD::sw-background — disc equilibrium (Sec. II.A) -------------------------------------------
include("background.jl")
export DiscBackground, rotation_profile, Omega, omega_d, Omega_emri, eps_profile, pressure, gamma1
export dlogp_dr_over_enthalpy, kappa2, r_isco, softening_length, F_J0, F_J1
# the EXISTING Modes generics gain DiscBackground methods (one name = one concept); re-exported here
export disc_OmegaK, kappar2, csound, eden0

include("eccentric.jl")
# ECC::gr-li-thermostat-sensitivity — thermostatted LI sensitivity diagnostics (a DAG sink); its tag is
# rejected by the primary closure dispatch of eccentric.jl, so it is included after that file
include("li_thermostat.jl")

# ---- EGD::sw-grid — adaptive corotation/WKB radial grid (App. C) ---------------------------------
include("grid.jl")
export SpiralGrid, build_grid, corotation_radius, corotation_block, smoothmin
export wkb_wavenumber, wkb_wavenumber2, wkb_wavenumber_floored, wkb_local, WKBRegion, wkb_region
export cell_count, GRID_EXTENTS

# ---- EGD::sw-master-matrices — relativistic master system (Sec. II.C) -----------------------------
# (included AFTER grid.jl: the Landau shift uses grid.jl's `corotation_radius`; master_derived.jl and
#  r2_derived.jl are emitted by capabilities/AccretionDisc/derivation — route R3, no external CAS)
include("master.jl")
include("generated/eccentric_adiabatic.jl")
include("locally_isothermal.jl")
export MasterInputs, master_inputs, master_matrices, master_matrices_newtonian, delta_u_phi_newtonian
export delta_u_phi, r2_context, dv_dr, rotation_derivs
export landau_shift, dOmega_dr

# ---- EGD::sw-singular-source — the EMRI singular field and its Fourier modes (Sec. II.D, App. B) -----
# (depends on background.jl only: softening_length, Omega_emri; the modes feed master_inputs(; hmodes))
include("source.jl")
export SingularFieldCoeffs, singular_field_coeffs, worldline_velocity, s0_squared, s0_squared_dr
export singular_field, singular_field_mode, source_modes, source_modes!, raise_modes
export strip_halfwidth, trapezoid_nodes
# ECC::gr-azimuth-projector + ECC::gr-source-harmonics — eccentric source bank and its
# coordinate-time harmonics (needs eccentric.jl, source.jl; new methods of the source generics above)
include("eccentric_source.jl")

# ---- EGD::sw-mode-solver — implicit-midpoint global solve + outgoing-wave BCs (Sec. II.E) ---------
# (needs master.jl for C, S and delta_u_phi, source.jl for the modes at the midpoints, grid.jl for r)
include("solver.jl")
# ECC::gr-boundary-certificate — arbitrary-frequency radiation rows (66)-(68), C-66; the matrix
# frequency-derivative `wkb_split` method that `outgoing_branch` routes through
include("boundary.jl")
export radiation_impedance_row
# ECC::gr-li-boundary-certificate — OPTION A outgoing/evanescent edge rows with the first transport
# (thermal-gradient) correction; needs locally_isothermal.jl and boundary.jl; explicit import only
include("li_boundary.jl")
# ECC::gr-mode-solver + ECC::gr-li-mode-solver — end-to-end eccentric projection, C-66 / OPTION A edge
# rows, midpoint BVP and closure-tagged reconstruction (needs eccentric_source.jl, boundary.jl and
# li_boundary.jl; new methods of solve_mode/reconstruct_fluid; explicit import only, no new exports)
include("eccentric_modes.jl")
export ModeSolution, solve_mode, midpoint_system, solve_midpoint, midpoint_residual
export eigen2, outgoing_branch, wkb_wavenumber_gr, wkb_wavenumber2_gr
export wkb_split, wkb_amplitudes, mode_amplitudes

# ---- EGD::sw-diagnostics — AMF (72a), torque density/integral (72b), (74), (75), cutoffs ----------
include("diagnostics.jl")
export sqrt_minus_g, amf, amf_mode, torque_density, torque_density_mode, cumulative_torque
export total_torque, lindblad_torque, torque_units, m_cut, balance_residual, corotation_split
export corotation_window
# ECC::gr-li-balance-diagnostics — OPTION A connected Reynolds wave flux and mean-transport split
# (needs locally_isothermal.jl and diagnostics.jl, whose eccentric context/solution work, torque
# and power methods belong to ECC::gr-adiabatic-balance-diagnostics; no new exports)
include("li_diagnostics.jl")

# ---- EGD::sw-survey-parallel — threaded m-sweep and configuration sweep (Sec. III) ----------------
include("survey.jl")
export ModeTorque, TorqueSurvey, torque_survey, survey_configs, mode_torques, mode_lindblad_torques
export compute_budget

# ---- EGD::sw-newtonian-limit — the M/r → 0 pipeline: (50) on a Newtonian background (Fig. 5) ------
# (after diagnostics.jl: it reuses `_newtonian_entries`/`_newtonian_delta_u_phi` of master.jl, the
#  `_kernel_integrals` projection of source.jl, the solver of solver.jl and `cumulative_torque` /
#  `corotation_split` of diagnostics.jl — one scheme, two models)
include("newtonian.jl")
export newtonian_Omega_emri, newtonian_csound, newtonian_pressure, newtonian_gamma1
export newtonian_rotation, newtonian_omega_d, newtonian_corotation_radius
export newtonian_potential_coeffs, newtonian_potential_mode, newtonian_potential_modes
export newtonian_master_matrices, newtonian_delta_u_phi, newtonian_delta_sigma
export newtonian_grid, newtonian_solve_mode
export newtonian_amf_mode, newtonian_torque_density_mode, newtonian_amf, newtonian_torque_density
export newtonian_balance_residual

# ---- EGD::sw-image-synthesis — mode-sum reconstruction of the wake (Figs. 1-2) --------------------
include("image_synthesis.jl")
export ModeInterp, mode_interp, synthesize, synthesize_cartesian, polar_to_cartesian, image_grid
export arm_phase, wake_modes

end # module SpiralWaves
